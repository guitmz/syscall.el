#!/usr/bin/env python3
"""Convert the API's full JSON dataset into a bundled Emacs Lisp file."""

import base64
import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path

source, destination = map(Path, sys.argv[1:3])
raw = source.read_bytes()
data = json.loads(raw)
kernels = {}

for row in data["kernels"]:
    kernels.setdefault(row["version"], []).append(row["arch"])
syscalls = defaultdict(list)

for row in data["syscalls"]:
    if (
        not isinstance(row.get("nr"), int)
        or not row.get("name")
        or not row.get("since")
    ):
        raise ValueError("Invalid syscall row")
    syscalls[row["arch"]].append(row)

if not kernels or not data["conventions"] or not syscalls:
    raise ValueError("Empty dataset")

arches = {arch for values in kernels.values() for arch in values}
if arches != set(syscalls):
    raise ValueError("Kernel and syscall architectures do not match")

bundle = {
    "kernels": [
        {"version": version, "arches": values} for version, values in kernels.items()
    ],
    "conventions": data["conventions"],
    "syscalls": syscalls,
}

encoded = base64.b64encode(
    json.dumps(bundle, ensure_ascii=False, separators=(",", ":")).encode()
).decode()
lines = "\n".join(encoded[i : i + 100] for i in range(0, len(encoded), 100))

destination.write_text(
    ";;; syscall-data.el --- Bundled syscall dataset  -*- lexical-binding: t; -*-\n\n"
    ";; Generated by scripts/build-dataset.py; do not edit.\n\n"
    ';;; Code:\n\n(defconst syscall-data--sha256 "'
    + hashlib.sha256(raw).hexdigest()
    + '"\n  "SHA256 of the source JSON dataset.")\n\n(defconst syscall-data--json\n  "'
    + lines
    + '"\n  "Base64-encoded JSON dataset bundled with syscall.el.")\n\n'
    "(provide 'syscall-data)\n;;; syscall-data.el ends here\n",
    encoding="utf-8",
)
